    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButton1ActionPerformed
    {//GEN-HEADEREND:event_jButton1ActionPerformed

        if (textFieldNuevoNombre.getText().isBlank()
                || textFieldNuevaDireccion.getText().isBlank()
                || textFieldNuevoRes.getText().isBlank())
        {
            MenuPrincipal.muestraMensaje("Escribe un nombre, responsable y dirección válidos");
            return;
        }

        String nomMarca = cmbBoxMarca.getSelectedItem().toString();
        String nomCiudad = cmbBoxCiudad.getSelectedItem().toString();
        String nomSuc = cmbBoxSucursal.getSelectedItem().toString();


        Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);
        Nodo ciudad = datos.getMultilista().busca(marca.getAbj(), nomCiudad);
        Nodo sucursalNodo = datos.getMultilista().busca(ciudad.getAbj(), nomSuc);

        if (sucursalNodo != null && sucursalNodo.getObj() instanceof Sucursal)
        {
            Sucursal suc = (Sucursal) sucursalNodo.getObj();

            // Actualizar propiedades del objeto
            suc.setNom(textFieldNuevoNombre.getText().trim());
            suc.setDir(textFieldNuevaDireccion.getText().trim());
            suc.setResponsable(textFieldNuevoRes.getText().trim());

            sucursalNodo.setEt(suc.getNom());

            MenuPrincipal.muestraMensaje("Sucursal modificada correctamente");

        } else
        {
            MenuPrincipal.muestraMensaje("Error al encontrar la sucursal");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

