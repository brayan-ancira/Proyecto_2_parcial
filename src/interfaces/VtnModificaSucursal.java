    private void cargarMarcas()
    {
        cmbBoxMarca.removeAllItems();
        Nodo aux = datos.getMultilista().getR();
        while (aux != null)
        {
            cmbBoxMarca.addItem(aux.getEt());
            aux = aux.getSig();
        }
        cmbBoxMarca.setSelectedIndex(-1);
    }

