    private void cmbBoxMarcaActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxMarcaActionPerformed
    {//GEN-HEADEREND:event_cmbBoxMarcaActionPerformed

        cmbBoxCiudad.removeAllItems();
        if (cmbBoxMarca.getSelectedIndex() != -1)
        {
            Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), cmbBoxMarca.getSelectedItem().toString());
            Nodo aux = marca.getAbj();
            while (aux != null)
            {
                cmbBoxCiudad.addItem(aux.getEt());
                aux = aux.getSig();
            }
        }
    }//GEN-LAST:event_cmbBoxMarcaActionPerformed

