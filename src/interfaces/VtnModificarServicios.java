    private void cmbBoxSucursalActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxSucursalActionPerformed
    {//GEN-HEADEREND:event_cmbBoxSucursalActionPerformed

        cmbBoxServicios.removeAllItems();

        String nomMarca = cmbBoxMarca.getSelectedItem().toString();
        String nomCiudad = cmbBoxCiudad.getSelectedItem().toString();
        String nomSuc = cmbBoxSucursal.getSelectedItem().toString();

        Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);
        if (marca != null)
        {
            Nodo ciudad = datos.getMultilista().busca(marca.getAbj(), nomCiudad);
            if (ciudad != null)
            {
                Nodo sucursal = datos.getMultilista().busca(ciudad.getAbj(), nomSuc);

                if (sucursal != null)
                {
                    Nodo auxServicio = sucursal.getAbj();
                    while (auxServicio != null)
                    {
                        if (auxServicio.getObj() instanceof Servicios)
                        {
                            Servicios serv = (Servicios) auxServicio.getObj();
                            cmbBoxServicios.addItem(serv.getNom());
                        }
                        auxServicio = auxServicio.getSig();
                    }
                }
            }
        }

        // Reseteamos el combo para que no quede nada seleccionado
        cmbBoxServicios.setSelectedIndex(-1);
    }//GEN-LAST:event_cmbBoxSucursalActionPerformed

    private void cmbBoxCiudadActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxCiudadActionPerformed
    {//GEN-HEADEREND:event_cmbBoxCiudadActionPerformed
        cmbBoxSucursal.removeAllItems();

        if (cmbBoxMarca.getSelectedItem() == null || cmbBoxCiudad.getSelectedItem() == null)
        {
            return;
        }

        String nomMarca = cmbBoxMarca.getSelectedItem().toString();
        String nomCiudad = cmbBoxCiudad.getSelectedItem().toString();

        Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);

        if (marca != null)
        {
            Nodo ciudad = datos.getMultilista().busca(marca.getAbj(), nomCiudad);

            if (ciudad != null)
            {
                Nodo auxSucursal = ciudad.getAbj();
                while (auxSucursal != null)
                {
                    cmbBoxSucursal.addItem(auxSucursal.getEt());
                    auxSucursal = auxSucursal.getSig();
                }
            }
        }

        cmbBoxSucursal.setSelectedIndex(-1);
    }//GEN-LAST:event_cmbBoxCiudadActionPerformed

