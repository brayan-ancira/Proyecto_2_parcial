    private void cmbBoxServiciosActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxServiciosActionPerformed
    {//GEN-HEADEREND:event_cmbBoxServiciosActionPerformed
        if (cmbBoxServicios.getSelectedItem() == null)
        {
            textFieldNomServicio.setText("");
            textFieldPrecioServicio.setText("");
            textFieldCupoServicio.setText("");
            return;
        }

        String nombreServicio = cmbBoxServicios.getSelectedItem().toString();

        String nomMarca = cmbBoxMarca.getSelectedItem().toString();
        String nomCiudad = cmbBoxCiudad.getSelectedItem().toString();
        String nomSuc = cmbBoxSucursal.getSelectedItem().toString();

        Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);
        Nodo ciudad = datos.getMultilista().busca(marca.getAbj(), nomCiudad);
        Nodo sucursal = datos.getMultilista().busca(ciudad.getAbj(), nomSuc);

        if (sucursal != null)
        {
            Nodo servicioNodo = datos.getMultilista().busca(sucursal.getAbj(), nombreServicio);

            if (servicioNodo != null && servicioNodo.getObj() instanceof Servicios)
            {
                Servicios serv = (Servicios) servicioNodo.getObj();

                textFieldNomServicio.setText(serv.getNom());
                textFieldPrecioServicio.setText(String.valueOf(serv.getPrecio()));
                textFieldCupoServicio.setText(serv.getCapacidad());
            }
        }
    }//GEN-LAST:event_cmbBoxServiciosActionPerformed

    private void btnGuardarCambiosModificarServiciosActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_btnGuardarCambiosModificarServiciosActionPerformed
    {//GEN-HEADEREND:event_btnGuardarCambiosModificarServiciosActionPerformed

        if (cmbBoxMarca.getSelectedItem() == null || cmbBoxCiudad.getSelectedItem() == null
                || cmbBoxSucursal.getSelectedItem() == null || cmbBoxServicios.getSelectedItem() == null)
        {
            MenuPrincipal.muestraMensaje("Selecciona todos los niveles y un servicio a modificar");
            return;
        }

        String nuevoNombre = textFieldNomServicio.getText().trim();
        String precioStr = textFieldPrecioServicio.getText().trim();
        String cupoStr = textFieldCupoServicio.getText().trim();

        if (nuevoNombre.isEmpty())
        {
            MenuPrincipal.muestraMensaje("El nombre del servicio no puede estar vacío");
            return;
        }

        if (!precioStr.matches("\\d+(\\.\\d+)?"))
        {
            MenuPrincipal.muestraMensaje("El precio debe ser un número entero o decimal (ej: 100 o 100.50)");
            return;
        }

        if (!cupoStr.matches("\\d+"))
        {
            MenuPrincipal.muestraMensaje("La capacidad (cupo) debe ser un número entero");
            return;
        }

        String nomMarca = cmbBoxMarca.getSelectedItem().toString();
        String nomCiudad = cmbBoxCiudad.getSelectedItem().toString();
        String nomSuc = cmbBoxSucursal.getSelectedItem().toString();
        String servicioOriginal = cmbBoxServicios.getSelectedItem().toString();

        Nodo marca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);
        Nodo ciudad = datos.getMultilista().busca(marca.getAbj(), nomCiudad);
        Nodo sucursal = datos.getMultilista().busca(ciudad.getAbj(), nomSuc);
        Nodo servicioNodo = datos.getMultilista().busca(sucursal.getAbj(), servicioOriginal);

        if (servicioNodo != null)
        {

            Servicios serv = (Servicios) servicioNodo.getObj();
            serv.setNom(nuevoNombre);
            serv.setPrecio((int) Double.parseDouble(precioStr));
            serv.setCapacidad(cupoStr);
            servicioNodo.setEt(nuevoNombre);

            MenuPrincipal.muestraMensaje("Servicio actualizado correctamente");
        } else
        {
            MenuPrincipal.muestraMensaje("Error: No se pudo localizar el servicio para modificar");
        }
    }//GEN-LAST:event_btnGuardarCambiosModificarServiciosActionPerformed

