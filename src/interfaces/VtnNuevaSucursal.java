    private void cmbBoxMarcasActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxMarcasActionPerformed
    {//GEN-HEADEREND:event_cmbBoxMarcasActionPerformed
       

    cmbBoxCiudades.removeAllItems();
    if (cmbBoxMarcas.getSelectedIndex() != -1)
    {
        String nomMarca = (String) cmbBoxMarcas.getSelectedItem();
        Nodo nodoMarca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);

        if (nodoMarca != null)
        {
            Nodo aux = nodoMarca.getAbj();
            while (aux != null)
            {
                cmbBoxCiudades.addItem(aux.getEt());
                aux = aux.getSig();
            }
        }
    }
    cmbBoxCiudades.setSelectedIndex(-1);
    }//GEN-LAST:event_cmbBoxMarcasActionPerformed

