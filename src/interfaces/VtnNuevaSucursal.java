    private void btnGuardarNuevaSucursalActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_btnGuardarNuevaSucursalActionPerformed
    {//GEN-HEADEREND:event_btnGuardarNuevaSucursalActionPerformed
        

    
        // 1. Validaciones básicas
        if (cmbBoxMarcas.getSelectedIndex() == -1 || cmbBoxCiudades.getSelectedIndex() == -1
                || textFieldNom.getText().isBlank() || textFieldDir.getText().isBlank() || textFieldRes.getText().isBlank())
        {
            MenuPrincipal.muestraMensaje( "Por favor completa todos los campos");
            return;
        }

        String nomMarca = (String) cmbBoxMarcas.getSelectedItem();
        String nomCiudad = (String) cmbBoxCiudades.getSelectedItem();
        String nomSuc = textFieldNom.getText().trim();
        String dir = textFieldDir.getText().trim();
        String res = textFieldRes.getText().trim();

        // 2. Crear objeto Sucursal
        Sucursal nuevaSuc = new Sucursal(nomSuc, dir, res);

        // 3. Insertar en Multilista
        // Construimos la ruta: Marca -> Ciudad -> Sucursal
        String[] ruta =
        {
            nomMarca, nomCiudad, nomSuc
        };
        Nodo nuevoNodo = new Nodo(nuevaSuc, nomSuc);

        datos.getMultilista().setR(
                datos.getMultilista().inserta(nuevoNodo, ruta, 0, datos.getMultilista().getR())
        );

        JOptionPane.showMessageDialog(this, "Sucursal creada con éxito");
        this.dispose(); // Cerrar ventana
    }//GEN-LAST:event_btnGuardarNuevaSucursalActionPerformed

