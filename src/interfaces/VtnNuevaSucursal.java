    private void llenarComboMarcas()
{
    cmbBoxMarcas.removeAllItems();
    Nodo aux = datos.getMultilista().getR();
    while (aux != null)
    {
        cmbBoxMarcas.addItem(aux.getEt());
        aux = aux.getSig();
    }
    cmbBoxMarcas.setSelectedIndex(-1);
}



