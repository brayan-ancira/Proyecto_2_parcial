    private void formWindowOpened(java.awt.event.WindowEvent evt)//GEN-FIRST:event_formWindowOpened
    {//GEN-HEADEREND:event_formWindowOpened
        cmbBoxMarca.removeAllItems();

        Nodo auxBusqueda = datos.getMultilista().getR();
        ArrayList<String> cadenas = new ArrayList<String>();

        while (auxBusqueda != null)
        {
            cadenas.add(auxBusqueda.getEt());
            auxBusqueda = auxBusqueda.getSig();
        }

        if (cadenas.size() != 0)
        {
            for (int i = 0; i < cadenas.size(); i++)
            {
                cmbBoxMarca.addItem(cadenas.get(i));
            }
        }
        cmbBoxMarca.setSelectedIndex(-1);
    }//GEN-LAST:event_formWindowOpened

    private void cmbBoxMarcaActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_cmbBoxMarcaActionPerformed
    {//GEN-HEADEREND:event_cmbBoxMarcaActionPerformed
        cmbBoxCiudadAEliminar.removeAllItems();

        String nomMarca = (String) cmbBoxMarca.getSelectedItem();

        if (nomMarca != null)
        {
            Nodo nodoMarca = datos.getMultilista().busca(datos.getMultilista().getR(), nomMarca);

            if (nodoMarca != null)
            {
                Nodo busquedaC = nodoMarca.getAbj();

                while (busquedaC != null)
                {

                    cmbBoxCiudadAEliminar.addItem(busquedaC.getEt());

                    busquedaC = busquedaC.getSig();
                }
            }
        }
        cmbBoxCiudadAEliminar.setSelectedIndex(-1);
    }//GEN-LAST:event_cmbBoxMarcaActionPerformed

