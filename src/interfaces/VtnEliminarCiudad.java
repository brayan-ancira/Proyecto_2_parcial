    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_btnEliminarActionPerformed
    {//GEN-HEADEREND:event_btnEliminarActionPerformed

            
        if (cmbBoxMarca.getSelectedIndex() == -1)
        {
            MenuPrincipal.muestraMensaje("Selecciona una marca primero");
            return; 
        }

        if (cmbBoxCiudadAEliminar.getSelectedIndex() == -1)
        {
            MenuPrincipal.muestraMensaje("Selecciona una ciudad");
            return; 
         }

  
        String nomMarca = (String) cmbBoxMarca.getSelectedItem();
        String nomCiudad = (String) cmbBoxCiudadAEliminar.getSelectedItem();

        String[] c =
        {
            nomMarca, nomCiudad
        };


        datos.getMultilista().elimina(c, 0, datos.getMultilista().getR());

        cmbBoxCiudadAEliminar.removeItem(nomCiudad);

        MenuPrincipal.muestraMensaje("Ciudad eliminada correctamente.");
    }//GEN-LAST:event_btnEliminarActionPerformed

